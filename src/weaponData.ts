export function buildInitialMagazineState(magId: string, loaded: boolean = true, ammoOverride?: string): MagazineItemState {
  const spec = MAGAZINE_SPECS[magId];
  if (!spec) {
    return {
      magTypeId: magId,
      caliber: '9x18',
      capacity: 8,
      rounds: [],
    };
  }
  const ammoId = ammoOverride && spec.compatibleAmmoIds.includes(ammoOverride) ? ammoOverride : spec.defaultAmmoId;
  return {
    magTypeId: spec.id,
    caliber: spec.caliber,
    capacity: spec.capacity,
    rounds: loaded ? Array.from({ length: spec.capacity }, () => ammoId) : [],
    hasIntegratedCo2: spec.hasIntegratedCo2,
    co2Pressure: spec.hasIntegratedCo2 ? (loaded ? 100 : 0) : undefined,
  };
}

export function createLoadedMagazineItem(magId: string, loaded: boolean = true, ammoOverride?: string): InventoryItem {
  const spec = MAGAZINE_SPECS[magId];
  const state = buildInitialMagazineState(magId, loaded, ammoOverride);
  const ammoSpec = AMMO_SPECS[spec.defaultAmmoId];
  const totalWeight = Number((spec.emptyWeightKg + state.rounds.length * (ammoSpec?.unitWeightKg || 0.01)).toFixed(3));
  return {
    id: `mag_${magId}_${Date.now()}_${Math.floor(Math.random() * 100000)}`,
    itemId: spec.id,
    name: spec.name,
    nameRu: spec.nameRu,
    category: 'ammo',
    count: 1,
    maxStack: 1,
    icon: 'magazine',
    description: spec.name,
    descriptionRu: spec.descriptionRu,
    effects: {},
    weight: totalWeight,
    volume: spec.volumeL,
    usable: true,
    magazineState: state,
  };
}

export function buildInitialWeaponState(weaponId: string, loaded: boolean = true): WeaponItemState {
  const spec = WEAPON_SPECS[weaponId];
  if (!spec) {
    return {
      weaponId,
      fireMode: 'semi',
      chamberedAmmoId: null,
      insertedMag: null,
      fouling: 0,
      barrelTempC: 20,
    };
  }

  let insertedMag: InventoryItem | null = null;
  let internalRounds: string[] | undefined = undefined;
  let chamberedAmmoId: string | null = null;
  let secondChamberAmmoId: string | null | undefined = undefined;

  if (spec.defaultMagId && (spec.feedType === 'detachable_mag' || spec.feedType === 'rotary_clip' || spec.feedType === 'linear_clip')) {
    insertedMag = createLoadedMagazineItem(spec.defaultMagId, loaded, spec.defaultAmmoId);
    if (loaded && spec.feedType === 'detachable_mag' && spec.weaponClass === 'firearm') {
      chamberedAmmoId = spec.defaultAmmoId;
    } else if (loaded && spec.weaponClass === 'pneumatic') {
      // Pneumatics feed directly from mag/clip on trigger or bolt cycle
      chamberedAmmoId = null;
    }
  } else if (spec.feedType === 'break_double') {
    chamberedAmmoId = loaded ? spec.defaultAmmoId : null;
    secondChamberAmmoId = loaded ? spec.defaultAmmoId : null;
  } else if (spec.feedType === 'break_single') {
    chamberedAmmoId = loaded ? spec.defaultAmmoId : null;
  } else if (spec.feedType === 'cylinder' || spec.feedType === 'internal_tube' || spec.feedType === 'internal_mag') {
    const cap = spec.internalCapacity || 5;
    if (spec.feedType === 'cylinder') {
      internalRounds = loaded ? Array.from({ length: cap }, () => spec.defaultAmmoId) : [];
      chamberedAmmoId = null;
    } else {
      internalRounds = loaded ? Array.from({ length: cap }, () => spec.defaultAmmoId) : [];
      chamberedAmmoId = loaded ? spec.defaultAmmoId : null;
    }
  }

  const state: WeaponItemState = {
    weaponId: spec.id,
    fireMode: spec.defaultFireMode,
    chamberedAmmoId,
    secondChamberAmmoId,
    insertedMag,
    internalRounds,
    spentShellsInCylinder: 0,
    fouling: 0,
    barrelTempC: 20,
    totalShotsFired: 0,
    isJammed: false,
    slideLockedOpen: false,
  };

  if (spec.propellant === 'co2_12g') {
    state.co2Pressure = loaded ? 100 : 0;
    state.co2TempPenalty = 0;
  } else if (spec.propellant === 'pcp_tank') {
    state.pcpPressureBar = loaded ? (spec.pcpMaxBar || 250) : 120;
    state.isCocked = loaded;
  } else if (spec.propellant === 'multi_pump') {
    state.pumpStrokes = loaded ? 6 : 0;
    state.isCocked = loaded;
  } else if (spec.propellant === 'spring_piston') {
    state.isCocked = loaded;
  } else if (spec.boltCycleSec) {
    state.isCocked = loaded;
  }

  return state;
}

export function getWeaponCurrentAmmoCount(item?: InventoryItem | null): {
  chamber: number;
  mag: number;
  maxMag: number;
  total: number;
  nextAmmoId: string | null;
} {
  if (!item || !item.weaponState) {
    return { chamber: 0, mag: 0, maxMag: 0, total: 0, nextAmmoId: null };
  }
  const spec = WEAPON_SPECS[item.itemId];
  const ws = item.weaponState;
  if (!spec) return { chamber: 0, mag: 0, maxMag: 0, total: 0, nextAmmoId: null };

  if (spec.feedType === 'break_double') {
    const c1 = ws.chamberedAmmoId ? 1 : 0;
    const c2 = ws.secondChamberAmmoId ? 1 : 0;
    return {
      chamber: c1 + c2,
      mag: 0,
      maxMag: 2,
      total: c1 + c2,
      nextAmmoId: ws.chamberedAmmoId || ws.secondChamberAmmoId || null,
    };
  }
  if (spec.feedType === 'break_single') {
    const c = ws.chamberedAmmoId ? 1 : 0;
    return { chamber: c, mag: 0, maxMag: 1, total: c, nextAmmoId: ws.chamberedAmmoId };
  }
  if (spec.feedType === 'cylinder') {
    const r = ws.internalRounds || [];
    return {
      chamber: 0,
      mag: r.length,
      maxMag: spec.internalCapacity || 6,
      total: r.length,
      nextAmmoId: r.length > 0 ? r[r.length - 1] : null,
    };
  }
  if (spec.feedType === 'internal_tube' || spec.feedType === 'internal_mag') {
    const c = ws.chamberedAmmoId ? 1 : 0;
    const r = ws.internalRounds || [];
    return {
      chamber: c,
      mag: r.length,
      maxMag: spec.internalCapacity || 5,
      total: c + r.length,
      nextAmmoId: ws.chamberedAmmoId || (r.length > 0 ? r[r.length - 1] : null),
    };
  }
  const c = ws.chamberedAmmoId ? 1 : 0;
  const magState = ws.insertedMag?.magazineState;
  const m = magState ? magState.rounds.length : 0;
  const maxM = magState ? magState.capacity : (spec.defaultMagId ? MAGAZINE_SPECS[spec.defaultMagId]?.capacity || 0 : 0);
  const topMag = magState && m > 0 ? magState.rounds[m - 1] : null;
  return {
    chamber: c,
    mag: m,
    maxMag: maxM,
    total: c + m,
    nextAmmoId: ws.chamberedAmmoId || topMag,
  };
}

export function getFireModeLabelRu(mode: WeaponFireMode): string {
  switch (mode) {
    case 'safe': return 'ПРЕД';
    case 'semi': return 'ОД';
    case 'burst': return 'ОЧ-3';
    case 'auto': return 'АВТ';
  }
}

export function getWeaponDisplaySubtitleRu(item: InventoryItem): string {
  const spec = WEAPON_SPECS[item.itemId];
  if (!spec || !item.weaponState) return '';
  const ws = item.weaponState;
  const counts = getWeaponCurrentAmmoCount(item);
  const parts: string[] = [spec.caliberRu];
  if (spec.feedType === 'break_double') {
    parts.push(`${counts.total}/2`);
  } else if (spec.feedType === 'break_single') {
    parts.push(counts.total > 0 ? 'Заряж.' : 'Пусто');
  } else if (spec.feedType === 'cylinder' || spec.weaponClass === 'pneumatic') {
    parts.push(`${counts.total}/${counts.maxMag}`);
  } else {
    parts.push(counts.chamber > 0 ? `${counts.mag}+1/${counts.maxMag}` : `${counts.mag}/${counts.maxMag}`);
  }
  if (spec.propellant === 'co2_12g') {
    const p = ws.insertedMag?.magazineState?.hasIntegratedCo2
      ? (ws.insertedMag.magazineState.co2Pressure ?? 0)
      : (ws.co2Pressure ?? 0);
    parts.push(`CO2 ${Math.round(p)}%`);
  } else if (spec.propellant === 'pcp_tank') {
    parts.push(`${Math.round(ws.pcpPressureBar ?? 0)} бар`);
  } else if (spec.propellant === 'multi_pump') {
    parts.push(`Качки ${ws.pumpStrokes ?? 0}/${spec.maxPumpStrokes || 10}`);
  } else if (spec.propellant === 'spring_piston') {
    parts.push(ws.isCocked ? 'Взвед.' : 'Не взв.');
  }
  parts.push(getFireModeLabelRu(ws.fireMode));
  return parts.join(' · ');
}

export function getWeaponEffectiveCo2(ws: WeaponItemState): number {
  if (ws.insertedMag?.magazineState?.hasIntegratedCo2) {
    return ws.insertedMag.magazineState.co2Pressure ?? 0;
  }
  return ws.co2Pressure ?? 0;
}

export function setWeaponEffectiveCo2(ws: WeaponItemState, val: number): void {
  const clamped = Math.max(0, Math.min(100, val));
  if (ws.insertedMag?.magazineState?.hasIntegratedCo2) {
    ws.insertedMag.magazineState.co2Pressure = clamped;
  } else {
    ws.co2Pressure = clamped;
  }
}

export function recalculateMagazineWeight(magItem: InventoryItem): void {
  if (!magItem.magazineState) return;
  const spec = MAGAZINE_SPECS[magItem.magazineState.magTypeId];
  if (!spec) return;
  let ammoKg = 0;
  for (const aid of magItem.magazineState.rounds) {
    ammoKg += AMMO_SPECS[aid]?.unitWeightKg || 0.01;
  }
  magItem.weight = Number((spec.emptyWeightKg + ammoKg).toFixed(3));
}

export function recalculateWeaponWeight(wpnItem: InventoryItem): void {
  if (!wpnItem.weaponState) return;
  const spec = WEAPON_SPECS[wpnItem.itemId];
  if (!spec) return;
  let extraKg = 0;
  const ws = wpnItem.weaponState;
  if (ws.insertedMag) {
    recalculateMagazineWeight(ws.insertedMag);
    extraKg += ws.insertedMag.weight || 0;
  }
  if (ws.chamberedAmmoId) {
    extraKg += AMMO_SPECS[ws.chamberedAmmoId]?.unitWeightKg || 0.01;
  }
  if (ws.secondChamberAmmoId) {
    extraKg += AMMO_SPECS[ws.secondChamberAmmoId]?.unitWeightKg || 0.01;
  }
  if (ws.internalRounds) {
    for (const aid of ws.internalRounds) {
      extraKg += AMMO_SPECS[aid]?.unitWeightKg || 0.01;
    }
  }
  wpnItem.weight = Number((spec.weightKg + extraKg).toFixed(3));
}
