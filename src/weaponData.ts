export interface AmmoSpec {
  id: string;
  caliber: string;
  caliberRu: string;
  name: string;
  nameRu: string;
  shortLabelRu: string;
  descriptionRu: string;
  weaponClass: WeaponClass;
  bulletType:
    | 'fmj'
    | 'jhp'
    | 'ap'
    | 'subsonic'
    | 'tracer'
    | 'sp'
    | 'sniper'
    | 'buckshot'
    | 'birdshot'
    | 'slug'
    | 'rubber'
    | 'lead'
    | 'bb_steel'
    | 'pellet_domed'
    | 'pellet_wadcutter'
    | 'pellet_pointed'
    | 'pellet_hollow'
    | 'pellet_heavy'
    | 'pellet_slug';
  caliberMm: number;
  massGrams: number;          // single projectile/pellet mass in grams
  pelletCount: number;        // 1 for bullet/slug/pellet; 9 for buckshot; 16 for birdshot
  spreadConeRad: number;      // intrinsic multi-pellet choke spread (0 for single bullet)
  velocityMult: number;       // multiplier on weapon baseline muzzle velocity
  dragCoeff: number;          // aerodynamic drag (1/m): high for BBs/birdshot, low for spitzer rifle bullets
  penetration: number;        // 0..100 (steel/bone/clothing/car penetration)
  expansion: number;          // 0.4..2.4 (soft-tissue wound cavity & bleeding multiplier)
  bluntFactor: number;        // 0.2..2.2 (blunt shock / bruise / knockdown)
  recoilMult: number;         // recoil momentum multiplier
  noiseMult: number;          // gunshot acoustic multiplier
  isNonLethal?: boolean;
  isTracer?: boolean;
  tracerColor?: string;
  isSteelBb?: boolean;
  ricochetBonus?: number;     // extra ricochet tendency (steel BBs & FMJ)
  casingColor: string;
  casingLengthPx: number;
  casingWidthPx: number;
  tipColor: string;
  boxColor: string;
  boxAccent: string;
  unitWeightKg: number;       // weight per round in kg
  maxStack: number;           // max stack count in inventory
  defaultPackCount: number;   // default spawned pack size
}

